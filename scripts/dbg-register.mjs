import { chromium } from '@playwright/test'
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
page.on('pageerror', e => console.log('PAGEERROR:', String(e).slice(0, 300)))
await page.goto('http://localhost:3100/login')
await page.fill('input:not([type="password"])', 'admin')
await page.fill('input[type="password"]', 'Admin@123')
await page.click('button[type="submit"]')
await page.waitForURL('http://localhost:3100/', { timeout: 8000 })

await page.goto('http://localhost:3100/apis/new')
await page.waitForSelector('input[placeholder="如：用户登录"]', { timeout: 8000 })
const ts = Date.now().toString(36)
await page.fill('input[placeholder="如：用户登录"]', '注册跳转测试-' + ts)
await page.fill('input[placeholder="/api/v1/resource/{id}"]', '/api/v1/reg-test/' + ts)
await page.fill('input[placeholder="http://10.0.0.11:8080/service/path"]', 'http://localhost:3100/upstream/echo')
await page.click('button:has-text("完成注册")')
await page.waitForTimeout(1200)
console.log('跳转后 URL:', page.url())
const bodyText = await page.evaluate(() => document.body.innerText.slice(0, 200))
console.log('页面内容:', JSON.stringify(bodyText))
await page.screenshot({ path: '../screenshot-after-register.png' })
await browser.close()
